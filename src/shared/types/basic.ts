/**
 * Тип, допускающий отсутствие значения (null или undefined).
 * Удобно для необязательных полей и результатов поиска/запросов.
 */
export type Nullable<T> = T | null

/**
 * Базовый тип «произвольный объект».
 * Маркер для функций и структур, работающих с любыми объектами,
 * без требования конкретных полей.
 */
export type BaseObject<Value = unknown> = Record<PropertyKey, Value>
